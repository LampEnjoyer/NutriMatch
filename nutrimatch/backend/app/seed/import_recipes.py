"""Load the imported recipe set (RecipeNLG subset) on top of the sample data.

Run from backend/, after the base seed:  python -m app.seed.import_recipes

The files are generated by tools/recipenlg/build.py. Validation runs first and nothing is written
if any check fails. Like the base seed this is idempotent: re-running updates records in place.
Curated ingredients from ingredients.json are never overwritten by imported ones.
"""

import sys

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db import SessionLocal
from app.models import Ingredient
from app.seed.seed import (
    SeedValidationError,
    _upsert_ingredients,
    _upsert_recipes,
    load_json,
    validate_ingredients,
    validate_recipes,
)


def run_import(session: Session) -> dict[str, int]:
    curated = load_json("ingredients.json")
    imported_ingredients = load_json("recipenlg_ingredients.json")
    imported_recipes = load_json("recipenlg_recipes.json")

    errors = validate_ingredients(imported_ingredients)
    curated_names = {item["normalized_name"] for item in curated["ingredients"]}
    imported_names = {item["normalized_name"] for item in imported_ingredients["ingredients"]}
    for name in sorted(curated_names & imported_names):
        errors.append(f"ingredient '{name}' is in both catalogs; the imported file must not redefine it")
    errors.extend(validate_recipes(imported_recipes, curated_names | imported_names))
    if len(errors) > 0:
        raise SeedValidationError(errors)

    _upsert_ingredients(session, imported_ingredients)
    catalog = {}
    for ingredient in session.scalars(select(Ingredient)):
        catalog[ingredient.normalized_name] = ingredient

    missing = sorted((curated_names | imported_names) - set(catalog))
    if len(missing) > 0:
        raise SeedValidationError(
            [f"ingredient '{name}' is not in the database; run python -m app.seed.seed first" for name in missing]
        )

    recipe_count = _upsert_recipes(session, imported_recipes, catalog)
    session.commit()
    return {"ingredients": len(imported_names), "recipes": recipe_count}


def main() -> int:
    session = SessionLocal()
    try:
        counts = run_import(session)
    except SeedValidationError as exc:
        session.rollback()
        print("Import data is invalid; nothing was written:", file=sys.stderr)
        for error in exc.errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    finally:
        session.close()

    print(f"Imported {counts['ingredients']} ingredients and {counts['recipes']} recipes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
